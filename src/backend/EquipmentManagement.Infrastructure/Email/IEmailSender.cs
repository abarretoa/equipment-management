namespace EquipmentManagement.Infrastructure.Email;

/// <summary>
/// Decouples callers from the concrete mail provider (docs/PROJECT_SPEC.md's
/// general "narrow interface" pattern, already used for
/// <c>Infrastructure.Files.IPrivateFileStorage</c> and
/// <c>Infrastructure.Documents.IResponsibilityTermPdfGenerator</c>; Phase 7 scope). Nothing in this interface — or anywhere calling
/// it — knows whether the real implementation is SMTP, Microsoft 365,
/// SendGrid, Postmark, or SES; swapping providers touches one implementation
/// class and one DI registration, never a caller.
/// </summary>
public interface IEmailSender
{
    /// <summary>
    /// Attempts to hand <paramref name="message"/> to the configured mail
    /// provider. Success means only "the provider accepted the send
    /// attempt" — never that the recipient received or read it (Phase 7 scope). Throws <see cref="EmailSendException"/> for any
    /// expected failure (missing configuration, the provider rejecting the
    /// message, a transient provider/network failure) — never a raw
    /// provider/SMTP exception, which could carry secrets (Phase 7 scope).
    /// </summary>
    Task SendAsync(EmailMessage message, CancellationToken cancellationToken = default);
}

/// <summary>One outbound email — deliberately minimal: one recipient, plain text, at most one attachment (Phase 7 scope; Attachment made optional for the Equipment Retirement Request notification, which carries no document). No CC/BCC/HTML — not needed by any workflow so far.</summary>
/// <param name="IncludeSignature">True for the Consultant-facing operational emails: the sender appends the configured corporate signature exactly once (see <see cref="EmailSignature"/>).</param>
public sealed record EmailMessage(string ToAddress, string Subject, string PlainTextBody, EmailAttachment? Attachment = null, bool IncludeSignature = false);

/// <summary>The attachment's exact bytes — never re-derived or regenerated by the sender (Phase 7 scope).</summary>
public sealed record EmailAttachment(string FileName, string ContentType, byte[] Content);
